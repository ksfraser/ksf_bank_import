<?php
/**
 * Regenerate the "Code Cross-Reference" section of every feature RTM from the
 * @BABOK tags that are actually present in the code.
 *
 * The section is the RTM -> code half of the traceability chain:
 *   FR  ->  implementing classes (from the @BABOK tags)  ->  UAT
 *
 * Usage:
 *   php tools/rtm_code_matrix.php            # report
 *   php tools/rtm_code_matrix.php --write    # rewrite the RTM files
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$options = getopt('', ['write']);
$write = isset($options['write']);

require_once __DIR__ . '/lib/code_units.php';
$index = require __DIR__ . '/lib/rtm_index.php';

$docRoot = $root . '/Project Documents';

/* Collect the FR references present in the code, per class. */
$byFr = [];
$it = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($root . '/src', FilesystemIterator::SKIP_DOTS)
);
$files = [];
foreach ($it as $f) {
    if (!$f->isFile() || $f->getExtension() !== 'php') {
        continue;
    }
    if (strpos($f->getPathname(), '/tests/') !== false) {
        continue;
    }
    $files[] = $f->getPathname();
}
sort($files);

foreach ($files as $path) {
    foreach (code_units($path) as $u) {
        if ($u['kind'] !== 'class' || $u['doc'] === null) {
            continue;
        }
        $doc = $u['doc'][2];
        if (stripos($doc, '@BABOK') === false) {
            continue;
        }
        if (!preg_match_all('/\bFR-[A-Z]*-?\d+\b/', $doc, $mm)) {
            continue;
        }
        foreach (array_unique($mm[0]) as $fr) {
            if (!isset($index[$fr])) {
                continue;
            }
            $byFr[$fr][$u['fqn']] = true;
        }
    }
}

$written = 0;

// Group the FRs by feature so each RTM gets one complete table.
$byFeature = [];
foreach ($index as $fr => $meta) {
    $byFeature[$meta['feature']][$fr] = $meta;
}

foreach ($byFeature as $feature => $frs) {
    $rtmFile = $docRoot . '/' . $feature . '/RTM.md';
    if (!is_file($rtmFile)) {
        continue;
    }
    $rows = [];
    $rows[] = '| FR | Requirement | BR | UAT | Implementing classes (`@BABOK` in `src/`) |';
    $rows[] = '|---|---|---|---|---|';
    foreach ($frs as $fr => $meta) {
        $classes = array_keys($byFr[$fr] ?? []);
        sort($classes);
        $short = array_map(static function (string $c): string {
            $pos = strrpos($c, '\\');
            return $pos === false ? $c : substr($c, $pos + 1);
        }, $classes);
        // Disambiguate when two trees declare a class with the same short name.
        $counts = array_count_values($short);
        $short = array_map(static function (string $c) use ($counts): string {
            $pos = strrpos($c, '\\');
            $name = $pos === false ? $c : substr($c, $pos + 1);
            return ($counts[$name] ?? 0) > 1 ? $c : $name;
        }, $classes);
        $rows[] = sprintf(
            '| %s | %s | %s | %s | %s |',
            $fr,
            $meta['title'],
            $meta['br'] ?? '—',
            $meta['uat'] ?? '— (no UAT case — see notes)',
            $classes === [] ? '**none — not implemented in the PSR-4 tree**' : implode(', ', $short)
        );
    }

    $section = "## Code Cross-Reference\n\n"
        . "Generated by `tools/rtm_code_matrix.php` from the `@BABOK` tags in the code.\n\n"
        . implode("\n", $rows) . "\n";

    $body = (string) file_get_contents($rtmFile);
    $marker = "## Code Cross-Reference";
    $pos = strpos($body, $marker);
    if ($pos !== false) {
        $body = substr($body, 0, $pos);
    }
    $body = rtrim($body) . "\n\n" . $section;

    if ($write) {
        file_put_contents($rtmFile, $body);
        $written++;
    } else {
        echo "--- $feature ---\n" . $section . "\n";
    }
}

if ($write) {
    printf("RTM files updated: %d\n", $written);
}
